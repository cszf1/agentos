export type ErrorCode = keyof typeof ERROR_STATUS;

/** Terminal reasons of a run (stored in runs.error_json.code). */
export type RunErrorCode =
  | "CANCELLED"
  | "DEADLINE_EXCEEDED"
  | "BUDGET_EXCEEDED"
  | "NO_APPLICATION_PUBLISHED"
  | "RECOVERY_BLOCKED"
  | "MODEL_UNAVAILABLE"
  | "MODEL_ERROR"
  | "NO_SYSTEM_PLAN_PREPARED"
  | "TARGET_CHANGED"
  | "QUEUE_EXPIRED"
  | "NO_MAINTENANCE_REPORT"
  | "NO_PROPOSAL"
  | "EXECUTION_EPOCH_STALE";

export interface ErrorBody {
  code: ErrorCode | RunErrorCode;
  message: string;
  retryable: boolean;
  details?: Record<string, unknown>;
}

const RETRYABLE: ReadonlySet<string> = new Set([
  "STORE_UNAVAILABLE", "MODEL_UNAVAILABLE", "RUN_BUSY", "APP_BUSY", "INSTANCE_NOT_READY", "SERVICE_UNAVAILABLE",
  "DEPLOYMENT_BUSY", "IMAGE_UNAVAILABLE", "SANDBOX_UNAVAILABLE",
  "PROVIDER_UNAVAILABLE", "BROKER_UNAVAILABLE", "RESOURCE_BUSY", "TELEMETRY_UNAVAILABLE", "CONTENT_UNAVAILABLE",
  "RUN_QUEUE_FULL", "TARGET_BUSY",   "POLICY_SYNC_PENDING", "CLOCK_UNCERTAIN", "ARTIFACT_GC_PENDING",
  "REGISTRY_NOT_SYNCED", "PERMIT_RECONCILING", "MACHINE_CAPACITY",
]);

export class AgentOsError extends Error {
  readonly code: ErrorCode;
  readonly status: number;
  readonly retryable: boolean;
  readonly details?: Record<string, unknown>;
  constructor(code: ErrorCode, message: string, details?: Record<string, unknown>) {
    super(message);
    this.name = "AgentOsError";
    this.code = code;
    this.status = ERROR_STATUS[code];
    this.retryable = RETRYABLE.has(code);
    this.details = details;
  }
  toBody(): ErrorBody {
    const body: ErrorBody = { code: this.code, message: this.message, retryable: this.retryable };
    if (this.details !== undefined) body.details = this.details;
    return body;
  }
}

export function isAgentOsError(e: unknown): e is AgentOsError {
  return e instanceof AgentOsError;
}
